"""G-6 / D-037 Step 9: the one benchmark table the PS asks for, generated from stored scores.

    python scripts/benchmark_table.py

For each model: F1, precision, recall and FPR of the compromise score (``y_within_K``) at the
deployable threshold - the causal expanding q90 (D-034) - plus threshold-free PR-AUC, on each
held-out compromise day (Thursday, Friday). Every cell is recomputed from the per-window held-out
scores in ``results/runs/`` with ``netwm.metrics.causal_threshold``; nothing is typed in.

Rows: logistic regression (E3 definition, deterministic), the shipped r2 checkpoint (E14's published
scores, seed 42), and the three-seed methods E19 (r2 method), E22, E20r, E26 (PCAP and CSV mode),
as mean with [min-max] over seeds 42/43/44. The same stored scores the scorecard reads.

Writes results/tables/benchmark_final.csv and results/tables/benchmark_final.md.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from netwm.data.processed import ProcessedDataset
from netwm.metrics import causal_threshold
from netwm.utils import RUNS, TABLES, save_run

DAYS = ("thursday", "friday")
SEEDS = (42, 43, 44)
ROWS = [
    ("Logistic regression (PS baseline)", "data/processed/cicids2017_m1v2", ["lr-flow-s42"], "per_day"),
    ("NetWM r2 - shipped checkpoint", "data/processed/cicids2017", ["e14-pmax-rescore-e4e7-worldmodel-r2"], "e14"),
    ("NetWM, r2 method (E19)", "data/processed/cicids2017_m1v2", [f"m1v2-e19-s{s}" for s in SEEDS], "per_day"),
    ("NetWM + factorised target (E22)", "data/processed/cicids2017_m1v2", [f"m1v2-e22-s{s}" for s in SEEDS], "per_day"),
    ("NetWM + real packets (E20r)", "data/processed/cicids2017_m1v2p", [f"m1v2-e20r-s{s}" for s in SEEDS], "per_day"),
    ("NetWM E22 + packets, PCAP input (E26)", "data/processed/cicids2017_m1v2p", [f"m1v2-e26-s{s}" for s in SEEDS], "per_day"),
    ("NetWM E22 + packets, CSV input (E26)", "data/processed/cicids2017_m1v2p", [f"m1v2-e26-s{s}-csvmode" for s in SEEDS], "per_day"),
]


def day_scores(run: str, kind: str) -> dict:
    m = json.loads((RUNS / run / "metrics.json").read_text(encoding="utf-8"))["metrics"]
    return {d: np.asarray(m["per_day"][d]["scores"], float) for d in DAYS}


def metrics(y: np.ndarray, score: np.ndarray) -> dict:
    alarm = score >= causal_threshold(score, 0.90)
    y = y.astype(bool)
    tp, fp = int((alarm & y).sum()), int((alarm & ~y).sum())
    fn, tn = int((~alarm & y).sum()), int((~alarm & ~y).sum())
    p = tp / (tp + fp) if tp + fp else 0.0
    r = tp / (tp + fn) if tp + fn else 0.0
    return {"f1": 2 * p * r / (p + r) if p + r else 0.0, "precision": p, "recall": r,
            "fpr": fp / (fp + tn) if fp + tn else 0.0, "pr_auc": float(average_precision_score(y, score))}


def main() -> None:
    rows = []
    for label, data, runs, kind in ROWS:
        ds = ProcessedDataset(data)
        for run in runs:
            scores = day_scores(run, kind)
            for day in DAYS:
                rows.append({"model": label, "run": run, "day": day, **metrics(ds.target(day), scores[day])})
    per_run = pd.DataFrame(rows)
    per_run.to_csv(TABLES / "benchmark_final.csv", index=False)

    lines = ["| model | day | F1 | precision | recall | FPR | PR-AUC |", "|---|---|---:|---:|---:|---:|---:|"]
    for (label, day), g in per_run.groupby(["model", "day"], sort=False):
        cells = []
        for col in ("f1", "precision", "recall", "fpr", "pr_auc"):
            v = g[col]
            cells.append(f"{v.mean():.3f}" if len(v) == 1 else f"{v.mean():.3f} [{v.min():.2f}-{v.max():.2f}]")
        lines.append(f"| {label} | {day.capitalize()} | " + " | ".join(cells) + " |")
    md = "\n".join(lines)
    note = ("\n\nCausal expanding q90 threshold (D-034) on the compromise score, label `y_within_K`; mean "
            "[min-max] over seeds 42/43/44 where three runs exist. Generated by `scripts/benchmark_table.py` "
            "from `results/runs/`.\n")
    (TABLES / "benchmark_final.md").write_text(md + note, encoding="utf-8")
    save_run("benchmark-final", {"rows": rows}, config={"rows": [(r[0], r[2]) for r in ROWS]})
    print(md)


if __name__ == "__main__":
    main()
